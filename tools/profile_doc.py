"""Write PROFILE.md (the profile format reference) from profile_spec.FIELDS, with the r5q values as examples.

    python profile_doc.py > ../PROFILE.md
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import profile_spec as spec  # noqa: E402

r5q = spec.load(HERE.parent / 'devices' / 'r5q.json', local=False)
print('# Device profile format (`toolkit/devices/<codename>.json`)\n')
print('Generated by `tools/profile_doc.py` from `tools/profile_spec.py`; the example column is the S10 Lite (r5q).')
print('Addresses and sizes are hex strings. `null` means unknown: `tools/validate_profile.py` lists it under the')
print('stages that need it. Private values (serial, absolute paths) go in `<codename>.local.json` under `local`.\n')
print('Stages: ' + ', '.join(f'`{s}`' for s in spec.STAGES) + '.\n')
section = None
for path, typ, stages, where in spec.FIELDS:
    top = path.split('.')[0]
    if top != section:
        section = top
        print(f'\n## {section}\n')
        print('| field | type | needed for | where it comes from | r5q |')
        print('|---|---|---|---|---|')
    v = spec.get(r5q, path)
    ex = '' if v is None else (str(v) if not isinstance(v, (list, dict)) else ('(list)' if isinstance(v, list) else '(table)'))
    if len(ex) > 40:
        ex = ex[:37] + '...'
    print(f'| `{path}` | {typ} | {", ".join(stages) or "-"} | {where.replace("|", "/")} | {ex.replace("|", "/")} |')
print('\n## local (private overlay, `<codename>.local.json`)\n')
print('| field | what |\n|---|---|')
for k, w in [('local.serial', 'adb serial of the test phone'), ('local.work_win', 'the work tree, Windows path'),
             ('local.work_wsl', 'the same tree as WSL sees it (/mnt/c/...)'), ('local.bundles_win', 'where bundles go'),
             ('local.backups_dir', 'backups/<serial>, relative to the work tree'), ('local.adb_dir', 'platform-tools')]:
    print(f'| `{k}` | {w} |')

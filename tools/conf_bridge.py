"""Bridge between this toolkit's JSON profiles and the donor's shell profiles (common/devices/<codename>.conf).

The donor (HackiOS / redwood-src; full working copy in WSL: /var/tmp/codex-ios-r5q/work/linux-source) describes
a device with plain shell variables that common/build.sh, common/run.sh and ./xl source: NAME KIND SOC
BOOT_VIA UEFI_TARGET UEFI_FD DTB FD_BASE FD_SIZE PAYLOAD_BASE FB_BASE WIFI_ATH11K BOOTARGS DEFAULT_SECS
USERLAND_VARS FIRMWARE AUTOBOOT_ARGS SMP (common/devices/_template.conf, docs/PORTING.md). The JSON profile
is a superset: its `donor` section holds exactly those, and the rest is what the donor format has no place for.

    python conf_bridge.py export ../devices/r5q.json -o ../devices/r5q.conf     # JSON -> donor .conf
    python conf_bridge.py import <linux-source>/common/devices/y2q.conf         # donor .conf -> JSON (stdout)
    python conf_bridge.py check  ../devices/y2q.json <linux-source>/common/devices/y2q.conf

What the export adds for a recovery-tested Samsung (r5q), beyond the donor's variables:
  KIND=phone-recovery   a new kind: common/build.sh still builds the kernel, loader and images (REST=1), skips
                        its step 4 (the `fastboot boot` image, KIND=phone only); the test image comes from
                        toolkit/generator instead
  BOOT_VIA=recovery-test  documents the boot path; never "twrp" (that writes the boot partition)
  a guard               the .conf refuses to be sourced by ./xl or common/run.sh: their phone paths do
                        `adb reboot bootloader` + fastboot, or write boot from TWRP -- both outside the
                        recovery-only rules (SAFETY.md). Runs go through the toolkit runner.
  IOSPORT_* variables   recovery-only flashing (partition, size, baseline hashes), the RAM ring and the log
                        slot, the USB RAM drive and the SD card, the resident image and kernel window, the
                        panel fixes (DSI reset register, DCS window, command buffer, autorefresh, flip
                        buffers), the virtual timer INTID, and IOSPORT_PROFILE (the full JSON)
The import reads a .conf as text (VAR=value lines); it never executes it.
"""
import argparse
import json
import pathlib
import re
import shlex
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import profile_spec as spec  # noqa: E402
from profile_spec import get, num  # noqa: E402

DONOR_VARS = ['NAME', 'KIND', 'SOC', 'BOOT_VIA', 'UEFI_TARGET', 'UEFI_FD', 'DTB', 'FD_BASE', 'FD_SIZE', 'PAYLOAD_BASE',
              'FB_BASE', 'WIFI_ATH11K', 'SMP', 'BOOTARGS', 'DEFAULT_SECS', 'USERLAND_VARS', 'FIRMWARE', 'AUTOBOOT_ARGS']
# donor variable -> profile path (FD/payload/FB live in the general sections; the rest in `donor`)
MAP = {'FD_BASE': 'memory.uefi_fd.base', 'FD_SIZE': 'memory.uefi_fd.size', 'PAYLOAD_BASE': 'memory.payload.base',
       'FB_BASE': 'loader.platform_struct.fb_base'}   # FB_BASE: the GOP framebuffer the loader identifies the phone by


def q(v):
    if v is None:
        return ''
    s = str(v)
    return s if re.fullmatch(r'[A-Za-z0-9_./:+-]*', s) else '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


def hx(v):
    n = num(v)
    return None if n is None else f'0x{n:X}'


def export(p: dict, profile_path: pathlib.Path) -> str:
    d = p.get('donor', {}) or {}
    codename = get(p, 'device.codename')
    kind, boot_via = d.get('kind', 'phone'), d.get('boot_via')
    lines = [f'# {get(p, "device.name")} ({codename}) -- donor-format profile, generated by',
             f'# toolkit/tools/conf_bridge.py from toolkit/devices/{profile_path.name}. Edit the JSON, not this file.',
             '# The donor variables come first (common/devices/_template.conf); IOSPORT_* are this port\'s extensions.']
    if kind == 'phone' and get(p, 'flash.test_partition') == 'recovery':
        # the toolkit's rules: tests from recovery only. Never the donor's fastboot/TWRP-boot paths for this phone.
        if boot_via and boot_via != 'recovery-test':
            lines.append(f'# (the donor runs this phone with KIND=phone BOOT_VIA={boot_via}; the toolkit does not)')
        kind, boot_via = 'phone-recovery', 'recovery-test'
    lines.append('')
    if kind != 'phone' and kind != 'qemu':
        lines += [
            '# Guard: this phone is tested from its recovery partition with automatic restore (toolkit/SAFETY.md).',
            '# ./xl and common/run.sh would reboot it to the bootloader for fastboot, or write its boot partition',
            '# from TWRP: refuse them here. common/build.sh (kernel, loader, REST=1 images) is fine.',
            'case "${0##*/}" in',
            f'xl|run.sh) echo "{codename}: recovery-tested phone; run tests with toolkit/runner (see toolkit/README.md)" >&2; exit 1 ;;',
            'esac', '']
    values = {
        'NAME': f'{get(p, "device.name")} ({codename}' + (f', {get(p, "device.model")})' if get(p, 'device.model') else ')'),
        'KIND': kind, 'SOC': d.get('soc') or f'Qualcomm {get(p, "device.soc_name")} ({(get(p, "device.soc") or "").upper()})',
        'BOOT_VIA': boot_via, 'UEFI_TARGET': d.get('uefi_target', codename), 'UEFI_FD': d.get('uefi_fd', ''),
        'DTB': d.get('dtb', ''), 'FD_BASE': hx(get(p, MAP['FD_BASE'])), 'FD_SIZE': hx(get(p, MAP['FD_SIZE'])),
        'PAYLOAD_BASE': hx(get(p, MAP['PAYLOAD_BASE'])),
        'FB_BASE': hx(get(p, MAP['FB_BASE']) or get(p, 'memory.display_reserved.base')),
        'WIFI_ATH11K': d.get('wifi_ath11k', 0), 'SMP': d.get('smp'), 'BOOTARGS': d.get('bootargs', ''),
        'DEFAULT_SECS': d.get('default_secs', 900), 'USERLAND_VARS': d.get('userland_vars', ''),
        'FIRMWARE': d.get('firmware', ''), 'AUTOBOOT_ARGS': d.get('autoboot_args'),
    }
    for k in DONOR_VARS:
        if values.get(k) is not None:
            lines.append(f'{k}={q(values[k])}')
    if kind == 'qemu':
        return '\n'.join(lines) + '\n'
    lines += ['', '# --- this port\'s extensions (toolkit) ----------------------------------------------------------']
    ext = [
        ('IOSPORT_PROFILE', f'toolkit/devices/{profile_path.name}', 'the full profile (every value, with sources)'),
        ('IOSPORT_MODEL', get(p, 'device.model'), 'the runner refuses any other ro.product.model'),
        ('IOSPORT_TEST_PARTITION', get(p, 'flash.test_partition'), 'the ONLY partition a test writes'),
        ('IOSPORT_RECOVERY_BYTES', get(p, 'flash.recovery_bytes'), 'test images are padded to it'),
        ('IOSPORT_RECOVERY_SHA256', get(p, 'baseline.recovery_sha256'), 'original recovery: restored after every run'),
        ('IOSPORT_BOOT_SHA256', get(p, 'baseline.boot_sha256'), 'verified, never written'),
        ('IOSPORT_VBMETA_SHA256', get(p, 'baseline.vbmeta_sha256'), 'verified, never written'),
        ('IOSPORT_ENTRY_METHOD', get(p, 'flash.method') or 'recovery', 'recovery: write+restore | fastboot-boot: RAM only'),
        ('IOSPORT_DOWNLOAD_RESTORE', 'RECOVERY only (original image, hash-checked)'
         if (get(p, 'flash.method') or 'recovery') == 'recovery' else None, 'Download Mode'),
        ('IOSPORT_LOG_RING', hx(get(p, 'memory.log_ring.base')), 'Samsung RAM ring (/proc/last_kmsg), warm resets keep it'),
        ('IOSPORT_LOG_SLOT', hx(get(p, 'log_slot.offset')), 'firmware log copy inside the test image (survives cold resets)'),
        ('IOSPORT_LOG_SLOT_MAGIC', get(p, 'log_slot.magic'), ''),
        ('IOSPORT_BOOTSHIM_INFO', hx(get(p, 'memory.bootshim_info')), 'BootShim progress record'),
        ('IOSPORT_LOADER_PE_BASE', hx(get(p, 'memory.loader_pe_base')), ''),
        ('IOSPORT_XNU_WINDOW', f'{hx(get(p, "memory.xnu_window.base"))}+{hx(get(p, "memory.xnu_window.size"))}'
         if get(p, 'memory.xnu_window.base') else None, 'the kernel window under the full firmware'),
        ('IOSPORT_RESIDENT_BASE', hx(get(p, 'memory.resident_image.base')), 'SYSTEM.APF lives here (md0)'),
        ('IOSPORT_USB_MSD_LABEL', get(p, 'firmware.usb_msd_label'), 'the PC copies SYSTEM.APF onto this USB RAM drive'),
        ('IOSPORT_USB_RAMDISK', hx(get(p, 'memory.usb_ramdisk.base')), ''),
        ('IOSPORT_SYSTEM_SOURCES', ' '.join(get(p, 'userland.system_sources') or []) or None,
         'where the firmware may take SYSTEM.APF from'),
        ('IOSPORT_GIC_VTIMER', get(p, 'gic.vtimer_intid'), 'the kernel needs gic_vtimer= when not 27'),
        ('IOSPORT_PANEL', f'{get(p, "display.width")}x{get(p, "display.height")}' if get(p, 'display.width') else None, ''),
        ('IOSPORT_DSI_RESET_REG', get(p, 'display.dsi_reset_reg'), 'DSI 6G registers are shifted by 4'),
        ('IOSPORT_PANEL_WINDOW', ' '.join((f'{k}:{v.replace(" ", "")}' if v else k) for k, v in (get(p, 'display.panel_window_dcs') or {}).items()
                                          if not k.startswith('_')) or None, 'DCS resent after the DSI reset'),
        ('IOSPORT_DSI_CMDBUF', hx(get(p, 'display.abl_command_buffer')), "the stock bootloader's command DMA buffer"),
        ('IOSPORT_AUTOREFRESH', hx(get(p, 'display.autorefresh')), ''),
        ('IOSPORT_FLIP_BUFFERS', ' '.join(hx(b) for b in get(p, 'display.flip_buffers') or []) or None, ''),
    ]
    for k, v, c in ext:
        if v is None or v == '':
            continue
        lines.append(f'{k}={q(v)}' + (f'   # {c}' if c else ''))
    return '\n'.join(lines) + '\n'


def parse_conf(text: str) -> dict:
    """VAR=value lines of a donor .conf, read as text (never executed)."""
    out = {}
    for line in text.splitlines():
        m = re.match(r'^([A-Z][A-Z0-9_]*)=(.*)$', line)
        if not m:
            continue
        raw = m.group(2)
        try:
            toks = shlex.split(raw, comments=True)
        except ValueError:
            toks = [raw]
        out[m.group(1)] = ' '.join(toks)
    return out


def import_conf(text: str, codename: str) -> dict:
    v = parse_conf(text)
    p = {'schema': 'iosport-device/1', '_about': f'imported from the donor profile {codename}.conf by conf_bridge.py',
         'device': {'codename': codename, 'prefix': codename, 'loader_platform': codename}, 'donor': {}}
    m = re.match(r'(.*?) \((.*)\)$', v.get('NAME', ''))
    if m:
        p['device']['name'] = m.group(1)
        model = re.search(r'\b(SM-\w+)', m.group(2))
        if model:
            p['device']['model'] = model.group(1)
    s = re.search(r'\((S[MD]M?\d{3,4})\)', v.get('SOC', ''))
    if s:
        p['device']['soc'] = s.group(1).lower()
    for k, path in MAP.items():
        if v.get(k):
            node = p
            parts = path.split('.')
            for part in parts[:-1]:
                node = node.setdefault(part, {})
            node[parts[-1]] = v[k]
    for k in DONOR_VARS:
        if k in v and k not in MAP and k != 'NAME':
            p['donor'][k.lower()] = int(v[k]) if v[k].isdigit() else v[k]
    return p


def check(p: dict, text: str):
    v = parse_conf(text)
    rows = []
    for k, path in list(MAP.items()) + [('BOOT_VIA', 'donor.boot_via'), ('UEFI_TARGET', 'donor.uefi_target'),
                                        ('BOOTARGS', 'donor.bootargs'), ('DEFAULT_SECS', 'donor.default_secs'),
                                        ('USERLAND_VARS', 'donor.userland_vars'), ('AUTOBOOT_ARGS', 'donor.autoboot_args')]:
        mine = get(p, path)
        theirs = v.get(k)
        if k == 'BOOT_VIA' and theirs is None:
            theirs = 'fastboot'      # ./xl's default when a profile does not say
        same = (num(mine) == num(theirs)) if k in MAP and mine and theirs else (str(mine or '') == str(theirs or ''))
        rows.append((k, theirs, mine, same))
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    e = sub.add_parser('export')
    e.add_argument('profile', type=pathlib.Path)
    e.add_argument('-o', '--out', type=pathlib.Path)
    i = sub.add_parser('import')
    i.add_argument('conf', type=pathlib.Path)
    c = sub.add_parser('check')
    c.add_argument('profile', type=pathlib.Path)
    c.add_argument('conf', type=pathlib.Path)
    a = ap.parse_args()
    if a.cmd == 'export':
        text = export(spec.load(a.profile, local=False), a.profile)
        if a.out:
            a.out.write_bytes(text.encode())
            print('wrote', a.out)
        else:
            sys.stdout.write(text)
    elif a.cmd == 'import':
        print(json.dumps(import_conf(a.conf.read_text(errors='replace'), a.conf.stem), indent=1))
    else:
        rows = check(spec.load(a.profile, local=False), a.conf.read_text(errors='replace'))
        for k, theirs, mine, same in rows:
            print(f'  {"same" if same else "DIFF"}  {k}: donor {theirs!r}, profile {mine!r}')
        return 0 if all(r[3] for r in rows) else 1


if __name__ == '__main__':
    sys.exit(main())

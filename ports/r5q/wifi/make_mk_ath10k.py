"""Derive mk-ath10k.sh (r5q: Linux ath10k SNOC on the donor's wifi/lx layer) from the donor's tools/mk-ath11k.sh.
First, measuring step: compile what compiles, list what fails and what is missing; nothing is linked into a kernel yet."""
import pathlib

here = pathlib.Path(__file__).parent
s = (here / 'mk-ath11k.orig.sh').read_text()


def sub(a, b, n=1):
    global s
    assert s.count(a) == n, (s.count(a), a[:70])
    s = s.replace(a, b)


sub('#!/bin/bash\n', '''#!/bin/bash
# r5q (Galaxy S10 Lite, SM8150): Linux's ath10k (SNOC: the WCN3990-family Wi-Fi inside the SoC, firmware on the modem),
# built the way tools/mk-ath11k.sh builds ath11k -- same Linux and FreeBSD releases, same layer (wifi/lx). This is the
# first, measuring step: how much of ath10k compiles on the layer, and what it then still wants (out/stubs.txt,
# out/missing.txt). Generated by work/ios-r5q/wifi/make_mk_ath10k.py from the donor's script.
# Usage: XNU_SRC=<kernel tree> WIFI_ROOT=<redwood-src> mk-ath10k.sh [fetch]
''')
sub('ROOT=$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)', 'ROOT=${WIFI_ROOT:-/var/tmp/codex-ios-r5q/work/redwood-src}')
sub('B=$ROOT/xnu-deps/build/ath11k', 'B=$ROOT/xnu-deps/build/ath10k')
sub('''	tar xJf linux-$VERSION.tar.xz -C unpacked --strip-components=1 linux-$VERSION/$ATH/ath11k \\
		linux-$VERSION/$ATH/spectral_common.h''', '''	tar xJf linux-$VERSION.tar.xz -C unpacked --strip-components=1 linux-$VERSION/$ATH/ath10k \\
		--wildcards "linux-$VERSION/$ATH/*.[ch]"''')
sub('	for f in unpacked/$ATH/ath11k/*.[ch] unpacked/$ATH/spectral_common.h; do', '	for f in unpacked/$ATH/ath10k/*.[ch] unpacked/$ATH/*.[ch]; do')
sub('		*"SPDX-License-Identifier: BSD-3-Clause-Clear"*) ;;', '		*"SPDX-License-Identifier: BSD-3-Clause-Clear"*) ;;\n		*"SPDX-License-Identifier: ISC"*) ;;')
sub('''	mv unpacked/$ATH/ath11k src/ath11k
	mv unpacked/$ATH/spectral_common.h src/''', '''	mv unpacked/$ATH/ath10k src/ath10k
	mkdir src/ath
	mv unpacked/$ATH/*.[ch] src/ath/
	cp src/ath/*.h src/''')
sub('[ "$1" = fetch ] && { echo "mk-ath11k.sh: ath11k of Linux $VERSION: $B/src/ath11k"; exit 0; }',
    '[ "$1" = fetch ] && { echo "mk-ath10k.sh: ath10k of Linux $VERSION: $B/src/ath10k"; exit 0; }')
sub('DRIVER="core hal qmi ce hw fw htc wmi mac reg peer dp dp_rx dp_tx hal_rx hal_tx dbring p2p"',
    'DRIVER="core ce htc htt htt_rx htt_tx mac wmi wmi-tlv txrx hw qmi qmi_wlfw_v01 snoc p2p bmi"\nATHLIB="main regd key"')
sub('''DFLAGS="-Isrc/ath11k -Isrc -include $W/include/lx_prelude.h -DCONFIG_ATH11K_AHB -DCONFIG_ATH11K_DEBUG
	-DKBUILD_MODNAME=\\"ath11k\\""''', '''R5Q=/mnt/c/Users/user/source/repos/WIP/S10-Lite-project/work/ios-r5q/wifi
DFLAGS="-I$R5Q/include -Isrc/ath10k -Isrc/ath -Isrc -include $W/include/lx_prelude.h -include $R5Q/include/lx_ath10k.h
	-DCONFIG_ATH10K_SNOC
	-DKBUILD_MODNAME=\\"ath10k\\""''')
sub('''for f in $DRIVER; do compile src/ath11k/$f.c obj/ath11k_$f.o $DFLAGS & done
for f in "$W"/src/*.c; do [ -f "$f" ] && compile "$f" obj/lx_$(basename "$f" .c).o $DFLAGS -I$W/src & done''',
    '''for f in $DRIVER; do compile src/ath10k/$f.c obj/ath10k_$f.o $DFLAGS & done
for f in $ATHLIB; do compile src/ath/$f.c obj/ath_$f.o $DFLAGS & done
# (wifi/lx/src/lx_bus.c is ath11k's bus; ath10k's snoc.c is its own -- measured without lx_bus.c)
for f in "$W"/src/lx_base.c "$W"/src/lx_80211.c "$W"/src/lx_wpa.c; do compile "$f" obj/lx_$(basename "$f" .c).o $DFLAGS -I$W/src & done
compile $R5Q/src/lx_snoc.c obj/lx_snoc.o $DFLAGS -I$W/src &''')
sub('''[ -z "$bad" ] || exit 1
OBJECTS=$(for f in $DRIVER; do echo obj/ath11k_$f.o; done; for f in "$W"/src/*.c; do echo obj/lx_$(basename "$f" .c).o; done)''',
    '''# measuring: every file that does not compile is listed above; the rest go on
OBJECTS=$(ls obj/*.o)
echo "mk-ath10k.sh: compiled $(ls obj/*.o | wc -l) files; failed: $(for f in obj/*.err; do [ -s $f ] && [ ! -f ${f%.err} ] && basename $f .o.err; done | tr '\\n' ' ')"''')
sub(': > out/stubs.txt\n', ': > out/stubs.txt\n: > out/missing.txt\n')
sub('	ath11k_*|__ath11k_*) ;;', '	ath10k_*|__ath10k_*|ath_*|ath11k_*|__ath11k_*) ;;')
sub('	*) echo "mk-ath11k.sh: nothing defines $s" >&2; missing=1; continue ;;', '	*) echo "$s" >> out/missing.txt; continue ;;')
sub('[ -z "$missing" ] || exit 1\n', 'echo "mk-ath10k.sh: $(wc -l < out/missing.txt) names nothing defines yet (out/missing.txt)"\n')
sub('CFLAGS="-mkernel', 'CFLAGS="-I/mnt/c/Users/user/source/repos/WIP/S10-Lite-project/work/ios-r5q/wifi/include -mkernel')
s = s.replace('out/ath11k.o', 'out/ath10k.o').replace('mk-ath11k.sh:', 'mk-ath10k.sh:')
(here / 'mk-ath10k.sh').write_text(s, newline='\n')
print('wrote mk-ath10k.sh')

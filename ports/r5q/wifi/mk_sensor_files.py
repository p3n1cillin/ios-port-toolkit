"""mk_sensor_files.py PERSIST_SENSORS_DIR OUT.h: the files the SLPI's sensor registry reads through FastRPC (served by the
kernel, redwood_adsp.c frpc_*), as a C table compiled into the kernel. PERSIST_SENSORS_DIR is the phone's own
/persist/sensors (debugfs rdump of the persist partition, work/ios-r5q/work-sensors/persist-sensors/sensors): device
data, kept local -- the table is generated into the kernel overlay at build time and goes nowhere else.
"""
import os
import sys

src, out = sys.argv[1], sys.argv[2]
files = []
reg = os.path.join(src, 'registry', 'registry')
for name in sorted(os.listdir(reg)):
    files.append(('/persist/sensors/registry/registry/' + name, open(os.path.join(reg, name), 'rb').read()))
for name in ('sns_reg_version',):
    p = os.path.join(src, 'registry', name)
    if os.path.exists(p):
        files.append(('/persist/sensors/registry/' + name, open(p, 'rb').read()))
for name in ('sensors_list.txt',):
    p = os.path.join(src, name)
    if os.path.exists(p):
        files.append(('/persist/sensors/' + name, open(p, 'rb').read()))
# (Test 220) the vendor partition's /etc/sensors (its sns_reg_config and config/*.json: what the registry is built from),
# when given as a third argument, and the platform values sns_reg_config names (this phone: an SM8150, soc_id 339, on
# Qualcomm's "MTP" platform; its sensor board revision 9, as its own registry's sns_hw_revision has it)
if len(sys.argv) > 3:
    vendor = sys.argv[3]
    for name in ('sns_reg_config', 'hals.conf'):
        files.append(('/vendor/etc/sensors/' + name, open(os.path.join(vendor, name), 'rb').read()))
    for name in sorted(os.listdir(os.path.join(vendor, 'config'))):
        files.append(('/vendor/etc/sensors/config/' + name, open(os.path.join(vendor, 'config', name), 'rb').read()))
    for path, text in (('/sys/devices/soc0/hw_platform', 'MTP'), ('/sys/devices/soc0/soc_id', '339'),
                       ('/sys/devices/soc0/platform_subtype', 'Unknown'), ('/sys/devices/soc0/platform_subtype_id', '0'),
                       ('/sys/devices/soc0/platform_version', '65536'), ('/sys/class/sensors/ssc_core/ssc_hw_rev', '9')):
        files.append((path, (text + '\n').encode()))

with open(out, 'w', newline='\n') as f:
    f.write('/* generated by wifi/mk_sensor_files.py from the phone\'s own /persist/sensors: do not edit, do not share */\n')
    f.write('static const struct {\n\tconst char *path;\n\tuint32_t length;\n\tconst uint8_t *data;\n} sensor_files[] = {\n')
    for path, data in files:
        body = ','.join(str(b) for b in data)
        f.write('\t{ "%s", %d, (const uint8_t[]){ %s } },\n' % (path, len(data), body if data else '0'))
    f.write('};\n')
print(f'{out}: {len(files)} files, {sum(len(d) for _, d in files)} bytes')
